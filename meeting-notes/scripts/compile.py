def parse_datetime(value: str) -> datetime | None:
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    except (ValueError, AttributeError):
        return None


def format_date(value: str) -> str:
    dt = parse_datetime(value)
    return dt.strftime("%Y-%m-%d %H:%M") if dt else value


def format_generated_at(note: dict, tz: str) -> str:
    dt = parse_datetime(note.get("metadata", {}).get("generated_at", ""))
    if not dt:
        return ""
    return dt.astimezone(ZoneInfo(tz)).strftime("%Y-%m-%d %H:%M:%S")


# --- Markdown ---------------------------------------------------------------


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def render_markdown(note: dict, *, lang: str = "ja", tz: str = "Asia/Tokyo") -> str:
    L = LABELS[lang]
    lines: list[str] = [f"# {note.get('title', '')}", ""]

    lines.append(f"- **{L['date']}**: {format_date(note.get('date', ''))}")
    if note.get("duration_seconds"):
        lines.append(
            f"- **{L['duration']}**: {note['duration_seconds'] // 60}{L['minutes_suffix']}"
        )
    if note.get("meeting_type"):
        label = L["meeting_type"].get(note["meeting_type"], note["meeting_type"])
        lines.append(f"- **{L['type']}**: {label}")
    if note.get("context"):
        lines.append(f"- **{L['context']}**: {note['context']}")
    lines.append("")

    if note.get("participants"):
        cols = L["participants_cols"]
        lines += [f"## {L['participants']}", "", f"| {' | '.join(cols)} |",
                  f"|{'|'.join('------' for _ in cols)}|"]
        for p in note["participants"]:
            role = L["role"].get(p.get("role", ""), p.get("role") or "")
            lines.append(
                f"| {_cell(p.get('name', ''))} | {_cell(role)} | {_cell(p.get('affiliation', ''))} |"
            )
        lines.append("")

    if note.get("participant_dynamics"):
        cols = L["dynamics_cols"]
        lines += [f"## {L['dynamics']}", "", f"| {' | '.join(cols)} |",
                  f"|{'|'.join('------' for _ in cols)}|"]
        for d in note["participant_dynamics"]:
            relation = L["relation"].get(d.get("relation", ""), d.get("relation", ""))
            lines.append(
                f"| {_cell(d.get('from', ''))} | {_cell(d.get('to', ''))} "
                f"| {_cell(relation)} | {_cell(d.get('topic', ''))} "
                f"| {_cell(d.get('detail', ''))} |"
            )
        lines.append("")

    if note.get("agenda"):
        lines += [f"## {L['agenda']}", ""]
        for i, item in enumerate(note["agenda"], 1):
            status = L["status"].get(item.get("status", ""), "")
            lines += [f"### {i}. {item.get('title', '')} {status}", ""]

            if item.get("summary"):
                lines += [f"**{L['summary']}**: {item['summary']}", ""]
            if item.get("speakers"):
                lines += [f"**{L['speakers']}**: {', '.join(item['speakers'])}", ""]

            if item.get("discussion_points"):
                lines += [f"#### {L['discussion_points']}", ""]
                lines += [f"- {point}" for point in item["discussion_points"]]
                lines.append("")

            if item.get("decisions"):
                lines += [f"#### {L['decisions']}", ""]
                for decision in item["decisions"]:
                    lines += [f"**{L['decision']}**: {decision.get('what', '')}", ""]
                    if decision.get("why"):
                        lines += [f"> **{L['why']}**: {decision['why']}", ""]
                    if decision.get("alternatives_considered"):
                        lines += [f"**{L['alternatives']}**:", ""]
                        lines += [
                            f"- ~~{alt.get('option', '')}~~ -- {alt.get('rejected_because', '')}"
                            for alt in decision["alternatives_considered"]
                        ]
                        lines.append("")
                    if decision.get("decided_by"):
                        lines += [f"**{L['decided_by']}**: {', '.join(decision['decided_by'])}", ""]

            if item.get("action_items"):
                cols = L["action_cols"]
                lines += [f"#### {L['action_items']}", "", f"| {' | '.join(cols)} |",
                          f"|{'|'.join('------' for _ in cols)}|"]
                for ai in item["action_items"]:
                    lines.append(
                        f"| {_cell(ai.get('owner', ''))} | {_cell(ai.get('task', ''))} "
                        f"| {_cell(ai.get('due', ''))} | {_cell(ai.get('context', ''))} |"
                    )
                lines.append("")

            if item.get("unresolved"):
                cols = L["unresolved_cols"]
                lines += [f"#### {L['unresolved']}", "", f"| {' | '.join(cols)} |",
                          f"|{'|'.join('------' for _ in cols)}|"]
                for u in item["unresolved"]:
                    lines.append(
                        f"| {_cell(u.get('issue', ''))} | {_cell(u.get('blocker', ''))} "
                        f"| {_cell(u.get('carry_forward_to', ''))} |"
                    )
                lines.append("")

    if note.get("key_takeaways"):
        lines += [f"## {L['takeaways']}", ""]
        lines += [f"- {t}" for t in note["key_takeaways"]]
        lines.append("")

    lines += ["---", ""]
    generated_by = note.get("metadata", {}).get("generated_by", "")
    if generated_by:
        generated_at = format_generated_at(note, tz)
        suffix = f" ({generated_at})" if generated_at else ""
        lines += [f"*{L['generated'].format(by=generated_by)}{suffix}*", ""]

    return "\n".join(lines)


