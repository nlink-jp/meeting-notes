def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("json_file", type=Path)
    parser.add_argument("-f", "--format", choices=["markdown", "html"], default="markdown")
    parser.add_argument("-o", "--output", type=Path, help="output file (default: stdout)")
    parser.add_argument("--lang", choices=sorted(LABELS), default="ja")
    parser.add_argument("--tz", default="Asia/Tokyo")
    args = parser.parse_args()

    note = json.loads(args.json_file.read_text(encoding="utf-8"))
    render = render_html if args.format == "html" else render_markdown
    output = render(note, lang=args.lang, tz=args.tz)

    if args.output:
        args.output.write_text(output, encoding="utf-8")
        print(f"compiled: {args.output}")
    else:
        print(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
